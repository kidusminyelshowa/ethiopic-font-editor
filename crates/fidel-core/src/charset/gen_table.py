def split(n):
    w=n.split(); last=w[-1]
    for v in ORDER:
        if last.endswith(v) and (len(last)>len(v) or len(w)>1):
            # labial forms on W-row (WA,WI..) only when stem before isn't empty
            cons=" ".join(w[:-1]+[last[:-len(v)]]).strip()
            return cons,v
    raise SystemExit("cannot split "+n)
